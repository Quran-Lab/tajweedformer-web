// Writes web/api/errors-catalogue.js from the error catalogue shared by the four SDKs.
//
//   node scripts/gen_errors.mjs <path to errors.json>
//
// The catalogue is embedded as its exact text (so a test can compare it with the shared file byte for byte)
// and never typed by hand. test/errors.test.mjs fails when the embedded copy differs from the shared file,
// and checks it against the SHA-256 written here where the shared file is not on disk (CI).
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) { console.error('usage: node scripts/gen_errors.mjs <errors.json>'); process.exit(2); }
const bytes = readFileSync(src);
const text = bytes.toString('utf8');
JSON.parse(text); // refuses a file that is not JSON
if (Buffer.compare(Buffer.from(text, 'utf8'), bytes) !== 0) throw new Error('errors.json is not UTF-8');
const sha = createHash('sha256').update(bytes).digest('hex');
const out = fileURLToPath(new URL('../web/api/errors-catalogue.js', import.meta.url));
writeFileSync(out, `// GENERATED by scripts/gen_errors.mjs from the shared error catalogue (errors.json). Do not edit.
/** The catalogue file's exact text (the first string of this file, so a reader that takes the first string gets the catalogue). */
export const ERRORS_JSON = ${JSON.stringify(text)};
/** SHA-256 of the catalogue file this was generated from. */
export const ERRORS_SHA256 = '${sha}';
`);
console.log(`web/api/errors-catalogue.js: ${bytes.length} bytes, sha256 ${sha}`);

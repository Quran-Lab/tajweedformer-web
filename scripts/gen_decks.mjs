// Bundle Quran Lab's sharing copy decks (<lang>.json, format quranlab.sharing-copy/1) into web/consent/decks.js,
// so the package needs no JSON imports.
//   node scripts/gen_decks.mjs <sharing_copy dir>     (or SHARING_COPY_DIR=<dir>)
// 2.0.1 bundles deck 2026-11-09.1 (consent share-2026-11-09). Refuses a deck in another format and any en or
// em dash.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
const dir = process.argv[2] || process.env.SHARING_COPY_DIR;
if (!dir) { console.error('usage: node scripts/gen_decks.mjs <sharing_copy dir>'); process.exit(2); }
const decks = {};
for (const f of readdirSync(dir).filter((x) => x.endsWith('.json')).sort()) {
  const d = JSON.parse(readFileSync(path.join(dir, f), 'utf8'));
  if (d.format !== 'quranlab.sharing-copy/1') throw new Error(`${f}: format ${d.format}`);
  if (/[\u2013\u2014]/.test(JSON.stringify(d.strings))) throw new Error(`${f}: an en or em dash`);
  decks[d.lang] = { format: d.format, version: d.version, lang: d.lang, dir: d.dir, consent_version: d.consent_version,
    delete_days: d.delete_days, ...(d.delete_timing ? { delete_timing: d.delete_timing } : {}), strings: d.strings, hadith_source: d.hadith_source };
}
const versions = new Set(Object.values(decks).map((d) => `${d.version} ${d.consent_version}`));
if (versions.size !== 1) throw new Error(`the decks disagree on version: ${[...versions].join(', ')}`);
const out = `// GENERATED by scripts/gen_decks.mjs from the sharing copy decks (quranlab.sharing-copy/1). Do not edit.\nexport const DECKS = ${JSON.stringify(decks, null, 1)};\n`;
writeFileSync(new URL('../web/consent/decks.js', import.meta.url), out);
console.log(`${Object.keys(decks).length} decks: ${Object.keys(decks).join(', ')} (${[...versions][0]})`);
